import Foundation

/// COBOL: a `*` or `/` in column 7 is a comment line, `*>` a floating comment; a literal ends at its
/// line's end (a `-` continuation line opens a fresh quote) and `""` / `''` are quotes inside one;
/// the divisions, verbs and reserved words (case-insensitive) — a dashed reserved word like `END-IF` stays a
/// keyword over the dashed-name and paragraph-name rules — level numbers, and `PIC` clauses as types, their
/// `9`s included.
extension RuleTables {
    static let cobol: [(String, TokenKind)] = [
        ("^.{6}\\*.*$", .comment),
        ("\\*>.*$", .comment),
        ("^.{6}/.*$", .comment),
        ("\"(?:[^\"\\n]|\"\")*(?:\"|(?=\\n)|\\z)", .string),
        ("'(?:[^'\\n]|'')*(?:'|(?=\\n)|\\z)", .string),
        ("\\b[A-Za-z][A-Za-z0-9]*-[A-Za-z0-9-]+\\b", .variable),
        ("^\\s*[A-Za-z0-9][A-Za-z0-9-]*\\.$", .function),
        (
            "(?i)\\b(IDENTIFICATION|ENVIRONMENT|DATA|PROCEDURE|DIVISION|PROGRAM-ID|AUTHOR|INPUT-OUTPUT|FILE-CONTROL|FILE|SECTION|WORKING-STORAGE|LINKAGE|FD|SD|SELECT|ASSIGN|TO|ORGANIZATION|ACCESS|MODE|IS|LINE|SEQUENTIAL|INDEXED|RELATIVE|RECORD|KEY|OPEN|INPUT|OUTPUT|I-O|EXTEND|CLOSE|READ|WRITE|REWRITE|DELETE|START|PERFORM|UNTIL|VARYING|FROM|BY|THRU|THROUGH|TIMES|END-PERFORM|END-READ|END-WRITE|END-IF|END-EVALUATE|END-CALL|END-STRING|END-UNSTRING|END-COMPUTE|MOVE|ADD|SUBTRACT|MULTIPLY|DIVIDE|COMPUTE|GIVING|ROUNDED|DISPLAY|ACCEPT|STOP|RUN|IF|ELSE|EVALUATE|WHEN|OTHER|AT|END|NOT|INVALID|VALUE|VALUES|ZERO|ZEROS|ZEROES|SPACE|SPACES|HIGH-VALUES|LOW-VALUES|INTO|INITIALIZE|STRING|UNSTRING|DELIMITED|SIZE|CALL|USING|RETURNING|EXIT|GO|BACK|GOBACK|CONTINUE|COPY|REDEFINES|OCCURS|DEPENDING|ON|SET|UP|DOWN|SEARCH|ALL|INSPECT|TALLYING|REPLACING|AND|OR|EQUAL|GREATER|LESS|THAN|SORT|MERGE|RELEASE|RETURN|COMP|COMP-3|BINARY|PACKED-DECIMAL|USAGE|ADDRESS|ADVANCING|AFTER|ALSO|ALTERNATE|ANY|ARE|AREA|AREAS|AS|ASCENDING|DESCENDING|BEFORE|CHARACTERS|CLASS|CLASS-ID|COLUMN|COMMA|COMP-1|COMP-2|COMP-4|COMP-5|COMPUTATIONAL|COMPUTATIONAL-3|CONFIGURATION|CONSTANT|CONTAINS|CONTENT|CORRESPONDING|CORR|CURRENCY|DECIMAL-POINT|DUPLICATES|DYNAMIC|END-ACCEPT|END-ADD|END-DELETE|END-DISPLAY|END-DIVIDE|END-MULTIPLY|END-RETURN|END-REWRITE|END-SEARCH|END-START|END-SUBTRACT|ENTRY|ERROR|EXCEPTION|FILE-CONTROL|FLOAT-LONG|FLOAT-SHORT|FOOTING|FOR|FUNCTION|FUNCTION-ID|GENERATE|GLOBAL|EXTERNAL|I-O-CONTROL|INITIAL|INVOKE|LABEL|LINAGE|LINES|LOCAL-STORAGE|METHOD-ID|NATIVE|NEXT|NUMERIC|ALPHABETIC|OBJECT|OF|IN|OVERFLOW|PIC|PICTURE|POINTER|PROGRAM|PROGRAM-POINTER|PROPERTY|RAISE|RAISING|RECORDS|REFERENCE|REPOSITORY|RESUME|SAME|SCREEN|SOURCE-COMPUTER|OBJECT-COMPUTER|SPECIAL-NAMES|STANDARD|STATUS|SYMBOLIC|TEST|THEN|TYPE|TYPEDEF|UPON|USE|WITH|WORKING-STORAGE|NULL|NULLS|SELF|SUPER|TRUE|FALSE|ALPHANUMERIC|NATIONAL|INDEX|COUNT|LENGTH|POSITION|ORDER|TO|EVERY|CYCLE|EXIT|SIGN|LEADING|TRAILING|SEPARATE|JUSTIFIED|BLANK|FILLER)\\b",
            .keyword
        ),
        ("^\\s*\\d{2}\\b", .number),
        ("\\b\\d+(\\.\\d+)?\\b", .number),
        ("(?i)\\bPIC(TURE)?\\s+(IS\\s+)?[XxAa9SsVvZz0-9()+,.$*-]+", .type),
    ]
}
