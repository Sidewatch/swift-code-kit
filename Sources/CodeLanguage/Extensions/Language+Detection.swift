    /// Detects the language of the file at `url` from its name and extension.
    /// Returns ``plainText`` when the file type is unrecognized. Never reads file contents.
    static func detect(for url: URL) -> Language {
        detect(filename: url.lastPathComponent)
    }

    /// Detects the language from a bare filename (e.g. `"main.swift"`, `"Makefile"`, `".env"`).
    ///
    /// Matching is case-insensitive and applies rules in precedence order:
    /// exact filename (`Makefile`, `tsconfig.json`) → prefix rules
    /// (`Dockerfile.*`, `.env.*`, `.dev.vars.*`) → compound extensions (`.blade.php`) →
    /// plain last extension. Returns ``plainText`` when nothing matches.
    static func detect(filename: String) -> Language {
        let name = filename.lowercased()
        if let l = Self.filenameMap[name] { return l }
        if name == "dockerfile" || name.hasPrefix("dockerfile.") { return .dockerfile }
        if name == ".env" || name.hasPrefix(".env.") { return .dotenv }
        // Cloudflare Wrangler's local secrets: `.dev.vars`, per environment `.dev.vars.staging`.
        if name == ".dev.vars" || name.hasPrefix(".dev.vars.") { return .dotenv }
        for (ext, lang) in Self.compoundExtensionMap where name.hasSuffix("." + ext) { return lang }
        if let dot = name.lastIndex(of: "."), dot < name.index(before: name.endIndex) {
            let ext = String(name[name.index(after: dot)...])
            if let l = Self.extensionMap[ext] { return l }
        }
        // Wrapper suffixes are transparent: `phpcs.xml.dist` / `config.yml.example`
        // are an XML and a YAML file wearing a marker extension, so when nothing
        // above matched, strip one wrapper and retry so the real extension decides.
        // Only reached when detection failed outright, so a wrapper name that IS
        // mapped (e.g. a future `.dist` language) still wins over the strip.
        if let dot = name.lastIndex(of: "."), dot > name.startIndex,
            Self.wrapperSuffixes.contains(String(name[name.index(after: dot)...]))
        {
            return detect(filename: String(name[..<dot]))
        }
        return .plainText
    }

